/** Ab dieser Länge Soft-Umbruch in zwei Zeilen (Wortgrenze nahe der Mitte). */
export const LIVE_STAND_TIP_WRAP_AT = 60;

export function pickLiveStandTip(exclude?: string): string {
  const pool =
    exclude && LIVE_STAND_TIPS.length > 1
      ? LIVE_STAND_TIPS.filter((t) => t !== exclude)
      : LIVE_STAND_TIPS;
  return pool[Math.floor(Math.random() * pool.length)] ?? LIVE_STAND_TIPS[0]!;
}

/**
 * Kurze Sprüche bleiben einzeilig; längere werden an einer natürlichen
 * Stelle nahe der Mitte umgebrochen (Dialog-Gedankenstrich, Satzzeichen, Leerzeichen).
 */
export function formatLiveStandTip(tip: string): string {
  const text = tip.trim();
  if (text.length <= LIVE_STAND_TIP_WRAP_AT) return text;

  const mid = Math.ceil(text.length / 2);
  const preferred = [" – ", " — ", ". ", "? ", "! ", ": ", ", ", " "];
  let bestAt = -1;
  let bestDist = Number.POSITIVE_INFINITY;

  for (const sep of preferred) {
    let from = 0;
    while (from < text.length) {
      const i = text.indexOf(sep, from);
      if (i < 0) break;
      const at = i + sep.length;
      if (at > 10 && at < text.length - 8) {
        const dist = Math.abs(at - mid);
        // Prefer earlier seps in the preferred list on equal distance.
        if (dist < bestDist) {
          bestDist = dist;
          bestAt = at;
        }
      }
      from = i + 1;
    }
    // Strong preference: if a high-priority sep lands within ~12 of mid, take it.
    if (bestAt >= 0 && preferred.indexOf(sep) <= 3 && bestDist <= 12) break;
  }

  if (bestAt <= 0) return text;
  return `${text.slice(0, bestAt).trimEnd()}\n${text.slice(bestAt).trimStart()}`;
}
